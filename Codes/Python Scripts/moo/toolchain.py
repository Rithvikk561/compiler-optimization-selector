"""
moo/toolchain.py — Toolchain verification for the MOO diagnostic.

Responsibilities:
  - Confirm clang and opt are present.
  - Record their versions.
  - Detect LLVM version mismatches between clang and opt.
  - Never silently fall back to a different tool.

This module is READ-ONLY with respect to the project — it does not
modify any existing files.
"""

from __future__ import annotations

import re
import subprocess
from typing import Optional

from .config import CLANG_PATH, OPT_PATH
from .models import IncompatibilityWarning, ToolInfo


# ---------------------------------------------------------------------------
# Version extraction helpers
# ---------------------------------------------------------------------------

def _version_string(path: str) -> str:
    """Return the raw version output for *path*, or an error message."""
    try:
        r = subprocess.run(
            [path, "--version"],
            capture_output=True, text=True, timeout=15
        )
        combined = (r.stdout + r.stderr).strip()
        return combined if combined else "<no version output>"
    except FileNotFoundError:
        return f"<file not found: {path}>"
    except Exception as exc:
        return f"<error: {exc}>"


def _extract_llvm_major(version_str: str) -> Optional[int]:
    """Extract the LLVM/clang major version number from a version string."""
    m = re.search(r"(?:clang|LLVM)\s+version\s+(\d+)", version_str, re.IGNORECASE)
    if m:
        return int(m.group(1))
    # Fallback: first bare "X.Y.Z"
    m = re.search(r"\b(\d+)\.\d+\.\d+\b", version_str)
    if m:
        return int(m.group(1))
    return None


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def probe_clang() -> ToolInfo:
    """Probe and return a ToolInfo for clang."""
    if not CLANG_PATH:
        return ToolInfo(name="clang", path=None, version_string="<not found>", found=False)
    ver = _version_string(CLANG_PATH)
    return ToolInfo(name="clang", path=CLANG_PATH, version_string=ver, found=True)


def probe_opt() -> ToolInfo:
    """Probe and return a ToolInfo for opt."""
    if not OPT_PATH:
        return ToolInfo(name="opt", path=None, version_string="<not found>", found=False)
    ver = _version_string(OPT_PATH)
    return ToolInfo(name="opt", path=OPT_PATH, version_string=ver, found=True)


def detect_incompatibilities(
    clang_info: ToolInfo,
    opt_info: ToolInfo,
) -> list[IncompatibilityWarning]:
    """
    Compare the two tool infos and return a list of detected incompatibilities.
    An empty list means no problems were found.
    """
    warnings: list[IncompatibilityWarning] = []

    if not clang_info.found:
        warnings.append(IncompatibilityWarning(
            kind="tool_missing",
            detail=f"clang not found. Searched paths include: {CLANG_PATH!r}. "
                   "Set TOACD_CLANG_PATH to override.",
        ))

    if not opt_info.found:
        warnings.append(IncompatibilityWarning(
            kind="tool_missing",
            detail=f"opt not found. Searched paths include: {OPT_PATH!r}. "
                   "Set TOACD_OPT_PATH to override.",
        ))

    if clang_info.found and opt_info.found:
        clang_major = _extract_llvm_major(clang_info.version_string)
        opt_major = _extract_llvm_major(opt_info.version_string)

        if clang_major is not None and opt_major is not None:
            if clang_major != opt_major:
                warnings.append(IncompatibilityWarning(
                    kind="version_mismatch",
                    detail=(
                        f"clang reports LLVM major version {clang_major} "
                        f"but opt reports LLVM major version {opt_major}. "
                        "IR generated by clang may not be accepted by opt. "
                        "This can cause custom-pass strategies to fail."
                    ),
                ))
        else:
            if clang_major is None:
                warnings.append(IncompatibilityWarning(
                    kind="version_parse_failure",
                    detail=f"Could not parse LLVM version from clang output: "
                           f"{clang_info.version_string!r}",
                ))
            if opt_major is None:
                warnings.append(IncompatibilityWarning(
                    kind="version_parse_failure",
                    detail=f"Could not parse LLVM version from opt output: "
                           f"{opt_info.version_string!r}",
                ))

    return warnings


def verify_toolchain() -> tuple[ToolInfo, ToolInfo, list[IncompatibilityWarning]]:
    """
    Top-level entry point: probe both tools and detect incompatibilities.
    Returns (clang_info, opt_info, warnings).
    """
    clang_info = probe_clang()
    opt_info = probe_opt()
    incompat = detect_incompatibilities(clang_info, opt_info)
    return clang_info, opt_info, incompat
